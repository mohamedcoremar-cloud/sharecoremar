ALTER TABLE public.order_status_history
  ADD COLUMN IF NOT EXISTS seq bigint GENERATED BY DEFAULT AS IDENTITY;

-- Backfill deterministic ordering for pre-existing rows.
WITH ordered AS (
  SELECT id, row_number() OVER (ORDER BY created_at, id) AS rn
    FROM public.order_status_history
)
UPDATE public.order_status_history h
   SET seq = o.rn
  FROM ordered o
 WHERE h.id = o.id AND h.seq IS NULL;

SELECT setval(pg_get_serial_sequence('public.order_status_history','seq'),
              COALESCE((SELECT MAX(seq) FROM public.order_status_history), 1));

CREATE INDEX IF NOT EXISTS order_status_history_order_seq_idx
  ON public.order_status_history (order_id, seq DESC);

CREATE OR REPLACE FUNCTION private.order_stage(_order_id uuid)
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT h.status FROM public.order_status_history h
   WHERE h.order_id = _order_id
     AND h.status IN ('queued_at_supplier','supplier_preparing','ready_for_pickup',
                      'accepted_by_logistics','picked_up_by_logistics','in_transit','delivered')
   ORDER BY h.seq DESC
   LIMIT 1;
$$;

CREATE OR REPLACE VIEW public.order_fulfillment_current
WITH (security_invoker = true) AS
SELECT DISTINCT ON (order_id)
    order_id,
    status AS stage,
    note,
    supplier_ready_eta,
    logistics_delivery_eta,
    driver_name,
    driver_phone,
    vehicle_info,
    created_at AS stage_at
  FROM public.order_status_history h
 WHERE status = ANY (ARRAY['queued_at_supplier','supplier_preparing','ready_for_pickup',
                           'accepted_by_logistics','picked_up_by_logistics','in_transit','delivered'])
 ORDER BY order_id, seq DESC;

REVOKE ALL ON FUNCTION private.order_stage(uuid) FROM PUBLIC, anon, authenticated;